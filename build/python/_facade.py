"""paintmix_py: hand-written façade over the generated ctypes bindings.

`_lowlevel.py` is regenerated by JuliaLibWrapping on every build; this file is
not. It turns the flat, caller-allocated ABI into small numpy-returning
helpers and wraps the one entrypoint (the model-info query) that the
generator leaves for a human, because its result is a struct.

Everything here mirrors `PaintMix`'s Julia API. See `build/README.md` for the
underlying buffer contract and `build/library.jl` for the entrypoints.

Scalar type: the entrypoints come in `f32` and `f64` flavors. These helpers
pick one from their array arguments — all float32 means the `f32` path, all
float64 the `f64` path — and default to float64 for plain Python sequences.
Pass `dtype=` to override. Nothing is ever silently computed in the other
precision.
"""

from dataclasses import dataclass

import numpy as np

from . import _lowlevel  # noqa: F401
from ._lowlevel import (  # noqa: F401
    CVector_borrowed_Float32,
    CVector_borrowed_Float64,
    JLWError,
    JLWStatus,
    ModelInfo,
)

# Status codes from `PaintMix`; the ABI contract is in `build/README.md`.
PM_OK = 0
PM_ERR_NULL = 1
PM_ERR_LENGTH = 2
PM_ERR_NONFINITE = 3
PM_ERR_WEIGHT = 4
PM_ERR_TOTAL = 5

__all__ = [
    "JLWError",
    "JLWStatus",
    "ModelInfo",
    "ModelDescription",
    "PM_OK",
    "PM_ERR_NULL",
    "PM_ERR_LENGTH",
    "PM_ERR_NONFINITE",
    "PM_ERR_WEIGHT",
    "PM_ERR_TOTAL",
    "abi_version",
    "model_info",
    "embedded_table_crc32",
    "encode",
    "decode",
    "mix",
    "bulk_mix",
    "weighted_mix",
    "rgb8_to_linear",
    "linear_to_rgb8",
]

_FLOAT_DTYPES = (np.dtype(np.float32), np.dtype(np.float64))


def abi_version() -> int:
    """The compiled ABI version."""
    return int(_lowlevel.paintmix_abi_version())


@dataclass(frozen=True)
class ModelDescription:
    """Provenance of the model compiled into the library."""

    abi_version: int
    format_version: int
    grid_n: int
    channel_count: int
    flags: int
    forward_crc32: int
    inverse_crc32: int
    model_id: bytes

    @property
    def model_id_hex(self) -> str:
        return self.model_id.hex()

    @property
    def forward_table_simplex_projected(self) -> bool:
        return bool(self.flags & 0x1)

    @property
    def inverse_table_largest_remainder(self) -> bool:
        return bool(self.flags & 0x2)


def _decode_message(buf) -> str:
    raw = bytes(buf)
    return raw.split(b"\x00", 1)[0].decode("utf-8", "replace")


def model_info() -> ModelDescription:
    """Grid size, payload checksums, generation flags, and model identifier."""
    info = _lowlevel.paintmix_model_info()
    if info.status.code != 0:
        raise JLWError(info.status.code, _decode_message(info.status.message))
    ident = int(info.model_id_lo).to_bytes(8, "little") + int(
        info.model_id_hi
    ).to_bytes(8, "little")
    return ModelDescription(
        abi_version=int(info.abi_version),
        format_version=int(info.format_version),
        grid_n=int(info.grid_n),
        channel_count=int(info.channel_count),
        flags=int(info.flags),
        forward_crc32=int(info.forward_crc32),
        inverse_crc32=int(info.inverse_crc32),
        model_id=ident,
    )


def embedded_table_crc32(index: int) -> int:
    """CRC-32 of an embedded table, recomputed from the live bytes.

    `index` is 0 for the inverse table and 1 for the forward table. The result
    must equal `model_info().inverse_crc32` / `.forward_crc32`; if it does not,
    the payload did not survive trimming or relocation.
    """
    from ._lowlevel import CVector_borrowed_UInt32

    out = np.zeros(1, dtype=np.uint32)
    _lowlevel.paintmix_table_crc32(int(index), CVector_borrowed_UInt32.from_numpy(out))
    return int(out[0])


def _dtype_of(arrays, dtype):
    if dtype is not None:
        dt = np.dtype(dtype)
        if dt not in _FLOAT_DTYPES:
            raise ValueError(f"dtype must be float32 or float64, got {dt}")
        return dt
    found = {np.asarray(a).dtype for a in arrays}
    floats = found & set(_FLOAT_DTYPES)
    if len(floats) > 1:
        raise ValueError("arguments mix float32 and float64; pass dtype= explicitly")
    if floats:
        return floats.pop()
    return np.dtype(np.float64)


def _convert(values, dt):
    arr = np.ascontiguousarray(values, dtype=dt)
    if arr.dtype == np.float32:
        carrier = CVector_borrowed_Float32
    else:
        carrier = CVector_borrowed_Float64
    return arr, carrier


def encode(rgb, dtype=None) -> np.ndarray:
    """Encode a linear-light RGB triple into seven scalars: c1..c4, r, g, b."""
    dt = _dtype_of([rgb], dtype)
    src, carrier = _convert(np.asarray(rgb).reshape(3), dt)
    out, out_carrier = _convert(np.zeros(7), dt)
    fn = (
        _lowlevel.paintmix_encode_f64
        if dt == np.float64
        else _lowlevel.paintmix_encode_f32
    )
    fn(carrier.from_numpy(src), out_carrier.from_numpy(out))
    return out


def decode(latent, dtype=None) -> np.ndarray:
    """Decode seven scalars (or a 7-element latent array) into linear RGB."""
    dt = _dtype_of([latent], dtype)
    src, carrier = _convert(np.asarray(latent).reshape(7), dt)
    out, out_carrier = _convert(np.zeros(3), dt)
    fn = (
        _lowlevel.paintmix_decode_f64
        if dt == np.float64
        else _lowlevel.paintmix_decode_f32
    )
    fn(carrier.from_numpy(src), out_carrier.from_numpy(out))
    return out


def mix(a, b, t, dtype=None) -> np.ndarray:
    """Mix two linear-light RGB colors; `t` is the share of `b`."""
    dt = _dtype_of([a, b], dtype)
    ca, carrier_a = _convert(np.asarray(a).reshape(3), dt)
    cb, carrier_b = _convert(np.asarray(b).reshape(3), dt)
    out, carrier_out = _convert(np.zeros(3), dt)
    if dt == np.float64:
        _lowlevel.paintmix_mix_f64(
            carrier_a.from_numpy(ca),
            carrier_b.from_numpy(cb),
            float(t),
            carrier_out.from_numpy(out),
        )
    else:
        _lowlevel.paintmix_mix_f32(
            carrier_a.from_numpy(ca),
            carrier_b.from_numpy(cb),
            np.float32(t),
            carrier_out.from_numpy(out),
        )
    return out


def bulk_mix(a, b, t, dtype=None) -> np.ndarray:
    """Vectorized mixing. `a` and `b` are `(n, 3)` or flat `3n`; `t` is `(n,)`."""
    dt = _dtype_of([a, b, t], dtype)
    ca, carrier_a = _convert(np.asarray(a).reshape(-1), dt)
    cb, carrier_b = _convert(np.asarray(b).reshape(-1), dt)
    ct, carrier_t = _convert(np.asarray(t).reshape(-1), dt)
    if ca.size != cb.size or ca.size != 3 * ct.size:
        raise ValueError("a and b must hold 3 channels per mixing fraction")
    out, carrier_out = _convert(np.zeros(ca.size), dt)
    if dt == np.float64:
        _lowlevel.paintmix_bulk_mix_f64(
            carrier_a.from_numpy(ca),
            carrier_b.from_numpy(cb),
            carrier_t.from_numpy(ct),
            carrier_out.from_numpy(out),
            ct.size,
        )
    else:
        _lowlevel.paintmix_bulk_mix_f32(
            carrier_a.from_numpy(ca),
            carrier_b.from_numpy(cb),
            carrier_t.from_numpy(ct),
            carrier_out.from_numpy(out),
            ct.size,
        )
    return out.reshape(-1, 3)


def weighted_mix(colors, weights, dtype=None) -> np.ndarray:
    """Weighted average of `n` colors in latent space."""
    dt = _dtype_of([colors, weights], dtype)
    cc, carrier_c = _convert(np.asarray(colors).reshape(-1), dt)
    cw, carrier_w = _convert(np.asarray(weights).reshape(-1), dt)
    if cc.size != 3 * cw.size:
        raise ValueError("colors must hold 3 channels per weight")
    out, carrier_out = _convert(np.zeros(3), dt)
    if dt == np.float64:
        _lowlevel.paintmix_weighted_mix_f64(
            carrier_c.from_numpy(cc),
            carrier_w.from_numpy(cw),
            carrier_out.from_numpy(out),
            cw.size,
        )
    else:
        _lowlevel.paintmix_weighted_mix_f32(
            carrier_c.from_numpy(cc),
            carrier_w.from_numpy(cw),
            carrier_out.from_numpy(out),
            cw.size,
        )
    return out


def rgb8_to_linear(rgb8) -> np.ndarray:
    """Encoded-sRGB bytes to linear light, evaluated in Float64.

    This mirrors `PaintMix.linear_from_srgb8` but is a host-side helper for
    image plumbing, not a bit-for-bit port of the Julia adapter.
    """
    c = np.asarray(rgb8, dtype=np.float64) / 255.0
    return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)


def linear_to_rgb8(rgb) -> np.ndarray:
    """Linear light to encoded-sRGB bytes: clip, transfer, round, clamp."""
    c = np.clip(np.asarray(rgb, dtype=np.float64), 0.0, 1.0)
    e = np.where(c <= 0.0031308, 12.92 * c, 1.055 * c ** (1 / 2.4) - 0.055)
    return np.clip(np.round(255.0 * e), 0, 255).astype(np.uint8)
